import assert from 'node:assert/strict';
import {getPatientHome} from '../src/lib/patient-home.ts';
const patient={id:'p1',hospitalId:'h1',name:'김OO',surgeryDate:'2026-09-16',dischargeDate:'2026-09-20'};
const today='2026-09-28';
const check=(id,date,extra={})=>({id,patientId:'p1',date,createdAt:date+'T12:00:00+09:00',pain:1,mobility:1,hasConcern:false,concernText:'',...extra});
const get=(checks=[],extra={})=>getPatientHome({patient,checks,today,...extra});
assert.deepEqual(get().states,['todayPending','normalRecovery']);
assert.equal(get().recoveryDays,12);
assert.equal(get([check('a','2026-09-27'),check('b',today),check('c',today),check('d','2026-09-29')]).weeklyDays,1);
assert.deepEqual(get([check('b',today)]).cardOrder,['recovery','help']);
assert.deepEqual(get().cardOrder,['help','recovery']);
assert.ok(get([check('other',today,{patientId:'p2'})]).states.includes('todayPending'));
assert.equal(get([], {patient:{...patient,nextAppointment:'2026-09-29T10:30'}}).appointmentMessage,'내일 진료가 있어요.');
assert.equal(get([], {patient:{...patient,nextAppointment:'2026-09-27'}}).appointmentMessage,null);
assert.equal(get([], {patient:{...patient,nextAppointment:'invalid'}}).appointmentMessage,null);
const signal={patientId:'p1',status:'open',type:'new_swelling',sourceCheckInIds:['a']};
assert.ok(get([check('a',today)],{signals:[signal]}).states.includes('symptomAlert'));
assert.ok(!get([check('a','2026-09-01')],{signals:[signal]}).states.includes('symptomAlert'));
assert.ok(!get([check('a',today)],{signals:[{...signal,type:'missed_checkin'}]}).states.includes('symptomAlert'));
assert.ok(!get([check('a',today)],{signals:[{...signal,status:'resolved'}]}).states.includes('symptomAlert'));
assert.match(get([check('a',today,{dayComparison:'better'})]).recoverySummary,/나아졌다고/);
assert.doesNotMatch(get([check('a',today,{dayComparison:'better',hasConcern:true})]).recoverySummary,/나아졌다고/);
assert.equal(get([], {patient:{...patient,surgeryDate:undefined}}).recoveryPoint,'퇴원');
assert.equal(get([], {patient:{...patient,surgeryDate:'invalid'}}).recoveryDays,null);
console.log('PASS patient home: states, week boundary, deduplication, future/other patient data, appointment, signals, missing dates');
